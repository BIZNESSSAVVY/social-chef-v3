const EMOJI={friendly:'👋',playful:'😋',bold:'🔥',classic:'🍽️',trendy:'✨',direct:'🍴'};
export function templateCandidates(data) {
 const tone=HOOKS[data.tone]?data.tone:'friendly';
 const hooks=HUMAN_ONLY.has(data.category)?PEOPLE_HOOKS:HOOKS[tone];
 const context=CONTEXT[data.category]||CONTEXT.Announcement;
 return hooks.map((hook,i)=>({id:`${HUMAN_ONLY.has(data.category)?'story':tone}:${i}`,render:()=>{
  const heading=hook+(data.emojis!==false?' '+EMOJI[tone]:'');
  const detail=data.description.trim();const name=data.restaurant?.trim();const link=data.link?.trim();
  const cta=data.cta?.trim()||'';
  const categoryLine=context[i%context.length];
  let chunks;
  if(data.length==='short') chunks=[heading,detail];
  else switch(i%4){
   case 0:chunks=[heading,categoryLine,detail];break;
   case 1:chunks=[heading,detail,categoryLine];break;
   case 2:chunks=[categoryLine,heading,detail];break;
   default:chunks=[heading,detail];
  }
  if(name)chunks.push(name);
  if(cta)chunks.push(cta.replace(/[.!?]+$/,'')+'.');
  if(link)chunks.push(link);
  if(data.hashtags!==false){const hash=data.category.replace(/[^a-zA-Z0-9]/g,'');chunks.push(`#${hash||'RestaurantLife'}`);}
  return chunks.filter(Boolean).join('\n\n');
 }}));
}
